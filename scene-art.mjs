import { STORY_YEARS } from './story-timeline.mjs';

function known(state, ...fields) {
  return state.life?.historyKnown === true || (state.lifeJournal || []).some(entry =>
    fields.every(field => Object.hasOwn(entry.set || {}, field)));
}
function portrait(id) { return id && SCENE_ART[id] ? { id, ...SCENE_ART[id] } : null; }
function yearOf(state, scene) {
  return Number.parseInt(scene?.year ?? state.lastResult?.year ?? state.journal?.at(-1)?.year
    ?? state.lifeJournal?.at(-1)?.year ?? STORY_YEARS[state.step] ?? '', 10);
}
function hobbyArt(state, year) {
  const life = state.life || {};
  if (!known(state, 'hobby') || !known(state, 'hobbyPractice') || life.hobbyPractice === 'dormant') return null;
  const activity = { table_tennis:'tennis', cooking:'cooking', walking:'walking', reading:'reading' }[life.hobby];
  if (!activity) return null;
  const stage = year >= 2026 ? 'if' : year >= 2024 ? 'senior' : year <= 1978 ? 'teen' : 'adult';
  const id = 'scene-' + stage + '-' + activity;
  return SCENE_ART[id] ? id : null;
}
function relationshipArt(state, year) {
  if (!known(state,'partner') || !known(state,'relationship')) return null;
  const life = state.life || {};
  const separate = life.relationship === 'separated' || life.marriageOutcome === 'divorced'
    || (life.livingArrangement === 'apart' && (life.marriageOutcome === 'considering' || life.relationshipRepair === 'space'));
  const paired = ['dating','married'].includes(life.relationship) && ['lori','maya'].includes(life.partner);
  if (year >= 2026) return 'scene-senior-' + (separate ? 'separate' : paired ? 'together' : 'alone');
  if (year >= 2024) return 'scene-2024-calendar';
  if (year <= 1984) return paired ? 'scene-young-together' : 'scene-young-alone';
  return 'scene-adult-' + (separate ? 'separate' : paired ? 'together' : 'alone');
}
function familyArt(state, year) {
  const life = state.life || {};
  if (!known(state,'children') || life.children !== 'parent' || !Number.isInteger(life.childStartYear)) return null;
  const childAge = year - life.childStartYear;
  // These are specific children, so a generic under-12 check would be false:
  // the two-child illustration depicts toddlers, the one-child one an infant.
  if (life.childCount === 2 && childAge >= 1 && childAge <= 3 && year >= 1992 && year <= 1993) return 'scene-family-two';
  if (life.childCount === 1 && childAge >= 0 && childAge <= 1 && year === 1999) return 'scene-family-one';
  return null;
}
function futurePath(state) {
  const f = state.flags || {};
  if (state.choicePlanEdition !== '2026.11.plans' || !f.if_2026_layoff
    || f.if_pivot_academic || f.if_pivot_ordinary) return null;
  const keys = ['nightlife','research','rival','president','solar'];
  const evidence = [...(state.evidence || [])].reverse().find(item => item.phase === 'choice'
    && item.step === 13 && /^if-2028-career-/.test(item.optionId));
  return evidence ? keys.find(key => evidence.optionId === 'if-2028-career-' + key + '-start') || null
    : keys.find(key => f['if_route_' + key]) || null;
}
function routeArt(state) {
  const f = state.flags || {}, path = futurePath(state);
  if (f.if_pivot_academic) return 'scene-senior-lab';
  if (f.if_pivot_ordinary) return 'scene-senior-alone';
  if (!path) return null;
  if (path === 'rival') {
    const finalJob = f.if_final_rival_hired || f.if_final_rival_niche_won || f.if_final_rival_partial;
    const hasJob = (finalJob || ((f.if_rival_hired || f.if_rival_contract || f.if_rival_lead || f.if_rival_specialist)
      && !f.if_rival_departed)) && !f.if_final_rival_failure;
    return hasJob ? 'scene-if-competitor' : f.if_rival_independent ? 'scene-2028-rebuild' : 'scene-if-review';
  }
  if (path === 'president' && !(f.if_president_residency || f.if_president_temporary || f.if_president_eligible
    || f.if_president_civic || f.if_final_president_civic || f.if_final_president_elected)) return 'scene-if-review';
  return {nightlife:'scene-if-nightlife',research:'scene-if-rival-lab',president:'scene-if-president',solar:'scene-if-business'}[path];
}
function careerArt(state, scene, year) {
  const f = state.flags || {};
  const result = state.phase === 'result';
  if (year >= 2026) {
    // An IF theme is already visible during the conversation, but losing the
    // job must wait for its actual committed flag, never a checked option.
    if (year === 2026) return result && f.if_2026_layoff ? 'scene-2026-accountability' : 'scene-if-review';
    if (result && (state.lastResult?.outcomeIndex === 2 || state.lastResult?.impact?.events?.some(event =>
      event.tone === 'crisis' && event.values?.career < 0))) return 'scene-senior-setback';
    if (f.future_memoir) return 'scene-2032-memoir';
    if (result && (f.future_retire || f.future_hobby)) return hobbyArt(state,year) || 'scene-2036-week';
    return routeArt(state) || (state.route === 'researcher' ? 'scene-senior-lab'
      : year === 2028 ? 'scene-2028-rebuild' : year === 2032 ? 'scene-2032-handoff' : 'scene-2036-week');
  }
  if (result && year >= 1993 && (state.lastResult?.outcomeIndex === 2
    || state.lastResult?.impact?.events?.some(event => event.tone === 'crisis' && event.values?.career < 0))) return year >= 2024 ? 'scene-2024-setback' : 'scene-adult-setback';
  if (year <= 1973) return 'scene-1973-letter';
  if (year <= 1978) return 'scene-1978-diner';
  if (year <= 1984) return 'scene-1984-lab';
  if (year === 1992) return /升职|职责|带队/.test(scene?.title || '') ? 'scene-1992-promotion' : 'scene-1992-study';
  if (year === 1993) return state.route === 'company' || /三个人|创业|LSI/.test(scene?.title || '') ? 'scene-1993-founders' : 'scene-young-lab';
  if (year === 1996) return state.route === 'researcher' ? 'scene-young-lab' : 'scene-1996-call';
  if (year === 1997) return state.route === 'researcher' ? 'scene-young-lab' : 'scene-1997-delivery';
  if (year === 1999) return state.route === 'company' ? 'scene-1999-stage' : 'scene-young-lab';
  if (year === 2007) return state.route === 'company' ? 'scene-2007-tools' : 'scene-2012-lab';
  if (year === 2012) return 'scene-2012-lab';
  if (year === 2016) return 'scene-2016-compute';
  if (year >= 2024) return 'scene-2024-calendar';
  return year >= 2007 ? 'scene-2012-lab' : 'scene-young-lab';
}
function personalArt(state, year) {
  const result = state.phase === 'life-result';
  const entry = state.lifeJournal?.at(-1);
  if (result && entry?.step === state.step) {
    const set = entry.set || {};
    if (set.children === 'parent' && familyArt(state,year)) return familyArt(state,year);
    if (Object.hasOwn(set,'relationship') || Object.hasOwn(set,'livingArrangement') || Object.hasOwn(set,'marriageOutcome')) {
      const relationship = relationshipArt(state,year);
      if (relationship) return relationship;
    }
    if (Object.hasOwn(set,'hobby') || Object.hasOwn(set,'hobbyPractice')) return hobbyArt(state,year)
      || (year >= 2026 ? 'scene-senior-alone' : year >= 2024 ? 'scene-2024-calendar' : year <= 1978 ? 'scene-1978-diner' : 'scene-adult-alone');
    if (set.lateLifeFocus === 'memoir' || set.memoirBoundary) return year >= 2026 ? 'scene-2032-memoir' : 'scene-2024-calendar';
  }
  if (year <= 1973) return 'scene-1973-letter';
  if (year <= 1978) return 'scene-1978-diner';
  if (year <= 1984) return 'scene-1984-lab';
  if (year === 1992) return 'scene-1992-study';
  if (year === 1993) return 'scene-1993-budget';
  if (year === 1996) return 'scene-1996-call';
  if (year === 1997) return hobbyArt(state,year) || 'scene-adult-alone';
  if (year === 1999) return relationshipArt(state,year) || 'scene-adult-alone';
  if (year === 2007) return 'scene-2007-listen';
  if (year === 2012) return 'scene-2012-parents';
  if (year === 2016) return 'scene-2016-adult';
  if (year === 2024) return hobbyArt(state,year) || 'scene-2024-calendar';
  if (year === 2026) return 'scene-2026-door';
  if (year === 2028) return relationshipArt(state,year) || 'scene-senior-alone';
  if (year === 2032) return 'scene-2032-memoir';
  if (year >= 2036) return hobbyArt(state,year) || 'scene-2036-week';
  return relationshipArt(state,year) || 'scene-adult-alone';
}

/** Presentation only. The caller supplies validated committed state and its
 * current scene; pending form/radio/checkbox selection is never an input. */
export function getSceneArt(state, scene = null, { ending = false } = {}) {
  if (!state) return null;
  const year = yearOf(state,scene);
  if (!Number.isFinite(year)) return null;
  if (ending || state.phase === 'ended') {
    if (state.endReason === 'IF终章：悲剧落幕') return null;
    if (!(state.lifeCourse?.history?.length || state.evidence?.length || state.lifeJournal?.length || state.journal?.length)) return null;
    const f = state.flags || {};
    if (year >= 2026) {
      if (f.future_memoir) return portrait('scene-2032-memoir');
      if (f.future_retire || f.future_hobby || state.endReason === 'IF终章：选择停在这里') return portrait(hobbyArt(state,year) || (year >= 2036 ? 'scene-2036-week' : 'scene-senior-alone'));
      if (state.lastResult?.outcomeIndex === 2) return portrait('scene-senior-setback');
      return portrait(routeArt(state) || 'scene-2036-week');
    }
    return portrait(personalArt(state,year));
  }
  return portrait(['life','life-result'].includes(state.phase) ? personalArt(state,year) : careerArt(state,scene,year));
}

